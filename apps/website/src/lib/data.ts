// ContextMatic lookups, from docs/contextmatic-lookups.md.
export interface Lookup {
  n: number;
  tool: string;
  query: string;
  confirmed: string;
  where: string;
  phase: string;
}
export function lookups(): Lookup[] {
  const out: Lookup[] = [];
  let phase = "";
  for (const line of read("docs/contextmatic-lookups.md").split("\n")) {
    if (line.startsWith("## ")) phase = line.slice(3);
    const m = /^\|\s*(\d+)\s*\|/.exec(line);
    if (!m) continue;
    const [n, tool, query, confirmed, where] = cells(line);
    out.push({ n: Number(n), tool, query, confirmed, where, phase });
  }
  return out;
}

// Real open-source repositories, from benchmark/real-repos (written by npm run benchmark:real).
export interface RealRepo {
  name: string;
  repo: string;
  why: string;
  commit: string;
  framework: string;
  calls: number;
  result: string;
  refused: boolean;
  scan: string;
  plan: string;
}
export function realRepos(): RealRepo[] {
  const list = JSON.parse(read("benchmark/real-repos/repos.json")) as { name: string; repo: string; subdir?: string; why: string; commit: string }[];
  const rows = read("benchmark/real-repos/README.md")
    .split("\n")
    .filter((l) => l.startsWith("| ["))
    .map(cells);
  return list.map((r) => {
    const row = rows.find((c) => c[0].startsWith(`[${r.name}]`));
    if (!row) throw new Error(`benchmark/real-repos/README.md has no row for ${r.name}`);
    const base = "https://github.com/Mrigank005/Portage/blob/main/benchmark/real-repos";
    return {
      name: r.name,
      repo: r.subdir ? `${r.repo}/tree/${r.commit}/${r.subdir}` : r.repo,
      why: r.why,
      commit: r.commit.slice(0, 7),
      framework: row[2],
      calls: Number(row[3]),
      result: row[4],
      refused: row[4].startsWith("Refused"),
      scan: `${base}/${r.name}/scan.md`,
      plan: `${base}/${r.name}/plan.md`,
    };
  });
}

// The MCP server's own description of its tools (generated by scripts/reference-data.mjs).
export interface SchemaProp {
  type?: string;
  enum?: string[];
  default?: unknown;
  description?: string;
  format?: string;
  items?: { type?: string };
  additionalProperties?: { type?: string };
  minimum?: number;
}
export interface Tool {
  name: string;
  title: string;
  description: string;
  inputSchema: { properties: Record<string, SchemaProp>; required?: string[] };
  annotations: { readOnlyHint?: boolean; destructiveHint?: boolean; idempotentHint?: boolean; openWorldHint?: boolean };
}
export const REF = reference as unknown as {
  server: { name: string; version: string };
  instructions: string;
  tools: Tool[];
  prompts: { name: string; title?: string; description?: string; arguments?: { name: string; description?: string; required?: boolean }[] }[];
  references: { name: string; filename: string; purpose: string; placement: string; packages: string; settings: string }[];
  cliHelp: string;
};

export function typeOf(p: SchemaProp): string {
  if (p.enum) return p.enum.map((v) => `"${v}"`).join(" | ");
  if (p.type === "array") return `${p.items?.type ?? "unknown"}[]`;
  if (p.type === "object" && p.additionalProperties) return `Record<string, ${p.additionalProperties.type ?? "unknown"}>`;
  if (p.format === "uri") return "string (URL)";
  return p.type ?? "unknown";
}

/** The CLI help text, split into commands: each has its usage lines and a description (from packages/cli/src/cli.ts). */
export interface CliCommand {
  name: string;
  usage: string[];
  description: string;
}
export function cliCommands(): CliCommand[] {
  const out: CliCommand[] = [];
  const add = (cmd: CliCommand, text: string) => (cmd.description += (cmd.description ? " " : "") + text);
  for (const raw of REF.cliHelp.split("\n")) {
    const line = raw.trim();
    if (/^ {2}portage /.test(raw)) {
      // "portage scan <path> [--json]      Report the Stripe code": the usage, then (maybe) its description after a wide gap.
      const [usage, ...desc] = line.split(/ {6,}/);
      const words = usage.split(/\s+/);
      out.push({ name: words.slice(0, words[1] === "relay" ? 3 : 2).join(" "), usage: [usage], description: desc.join(" ") });
    } else if (out.length && /^ {20,}\S/.test(raw)) add(out[out.length - 1], line);
    else if (out.length && /^ {2,19}\S/.test(raw)) out[out.length - 1].usage.push(line);
  }
  return out;
}

/** Splits a usage string into pieces that can wrap between options, never inside one. */
export const usageTokens = (usage: string) => usage.match(/\[[^\]]*\](?:\.{3})?|\S+/g) ?? [];
