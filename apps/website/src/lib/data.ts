// Data for the docs, benchmark and reference pages, read from the repository at build time.
import fs from "node:fs";
import path from "node:path";
import { REPO } from "./repo";
import reference from "../data/reference.json";

const read = (p: string) => fs.readFileSync(path.join(REPO, p), "utf8").replace(/\r\n/g, "\n");

/** Lets long identifiers wrap after dots, underscores and slashes (a <wbr> is not copied with the text). */
export const brk = (s: string) => s.replace(/([._/])(?=\w)/g, "$1<wbr>");

/** Inline Markdown (code, bold, links) to HTML, for text that comes from the repository's own Markdown files. */
export function inline(md: string): string {
  const esc = md.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  return esc
    .replace(/`([^`]+)`/g, (_m, c: string) => `<code>${brk(c)}</code>`)
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (_m, text: string, href: string) => {
      const url = /^https?:/.test(href) ? href : `https://github.com/Mrigank005/Portage/blob/main/docs/${href}`;
      return `<a href="${url}">${text}</a>`;
    });
}

/** Splits a Markdown table row on unescaped pipes. */
function cells(row: string): string[] {
  return row
    .trim()
    .replace(/^\||\|$/g, "")
    .split(/(?<!\\)\|/)
    .map((c) => c.trim().replace(/\\\|/g, "|"));
}

