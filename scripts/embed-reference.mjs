// Embeds packages/core/reference/* into packages/core/src/reference-sources.ts, so the bundled MCP server can hand
// the reference code to agents without reading files next to itself. Run after editing a reference file:
//   npm run reference:embed
// A test fails if the embedded copy is out of date.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const core = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../packages/core");
const dir = path.join(core, "reference");
const files = fs.readdirSync(dir).filter((f) => /\.(ts|tsx|js)$/.test(f)).sort();
const entries = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n"))},`);
const out = `// Generated by scripts/embed-reference.mjs from packages/core/reference. Do not edit by hand.\nexport const REFERENCE_SOURCES: Record<string, string> = {\n${entries.join("\n")}\n};\n`;
fs.writeFileSync(path.join(core, "src", "reference-sources.ts"), out);
console.log(`Embedded ${files.length} reference files`);
